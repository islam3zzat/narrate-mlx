"""Markdown report from a workdir's fact ledger (the lossless record next to a video). Standard library only, pure.

    render_report(ledger, coverage=None) -> str

Everything that comes from the source text (fact text, quotes, owners, ...) is untrusted: `esc` neutralises Markdown
and HTML so a quote cannot add a link, heading, image, table cell or tag to the report.
"""
from __future__ import annotations

import re

MARKER = "<!-- narrate-report: generated by `explainer.py report`; edits are overwritten -->"
KINDS = ("event", "decision", "action", "owner", "number", "system", "root_cause", "factor", "mitigation",
         "open_question", "contradiction", "ambiguity")
_ESCAPE = re.compile(r"([\\`*_{}\[\]<>|~&!])")


def esc(value) -> str:
    """One line of plain text that Markdown and HTML renderers show literally."""
    s = re.sub(r"[\x00-\x1f\x7f\u2028\u2029]+|\s+", " ", str(value if value is not None else "")).strip()
    s = _ESCAPE.sub(r"\\\1", s)
    s = s.replace("://", "\\://").replace("@", "\\@")                     # no autolinks
    s = re.sub(r"(?i)\bwww\.", lambda m: m.group(0)[:-1] + "\\.", s)      # no bare www. autolinks
    s = re.sub(r"^(#|-|\+|=)", lambda m: "\\" + m.group(1), s)            # no heading/list/quote at the start
    s = re.sub(r"^(\d+)([.)])", lambda m: m.group(1) + "\\" + m.group(2), s)   # "1." becomes "1\." so it is not a list marker
    return s


def _facts(ledger) -> tuple[list[dict], int]:
    raw = ledger.get("facts") if isinstance(ledger, dict) else None
    facts = [f for f in raw if isinstance(f, dict) and f.get("id")] if isinstance(raw, list) else []
    return facts, (len(raw) - len(facts)) if isinstance(raw, list) else 0


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def _plain(v) -> str:
    return re.sub(r"[^A-Za-z0-9_./ -]", "?", str(v))[:200]


def _id(f: dict) -> str:
    return f"`{re.sub(r'[^A-Za-z0-9_-]', '?', str(f['id']))}`"


def render_report(ledger, coverage: dict[str, list[str]] | None = None) -> str:
    facts, skipped = _facts(ledger)
    coverage = coverage or {}
    by_id = {str(f["id"]): f for f in facts}
    kind = lambda k: [f for f in facts if f.get("kind") == k]
    deferred = [f for f in facts if f.get("deferred")]
    src = ledger.get("source") if isinstance(ledger, dict) else None
    covered = lambda f: ", ".join(esc(x) for x in coverage.get(str(f["id"]), [])) or ("deferred to this report" if f.get("deferred") else "not narrated")

    L = [MARKER, "", "# Fact report", ""]
    L.append("Source: " + (f"`{_plain(src)}`" if src else "not recorded"))
    L += ["", "## Counts", ""]
    narrated = sum(1 for f in facts if coverage.get(str(f["id"])))
    report_only = sum(1 for f in deferred if not coverage.get(str(f["id"])))
    L += [f"- Facts: {len(facts)} ({sum(1 for f in facts if f.get('importance') == 'high')} high importance, "
          f"{sum(1 for f in facts if f.get('importance') == 'low')} low)",
          f"- Narrated in a video: {narrated}; deferred to this report only: {report_only}; in neither: {len(facts) - narrated - report_only}"]
    if skipped:
        L.append(f"- Entries skipped because they are not facts with an id: {skipped}")
    L += [""] + _table(["Kind", "Count"], [[k.replace("_", " "), str(len(kind(k)))] for k in KINDS if kind(k)]
                       + [["other", str(sum(1 for f in facts if f.get("kind") not in KINDS))]] * (1 if any(f.get("kind") not in KINDS for f in facts) else 0))

    timeline = [f for f in facts if f.get("kind") == "event" or (f.get("kind") == "mitigation" and f.get("at"))]
    L += ["## Timeline", "", "Events in ledger order; times are as the source gave them.", ""]
    L += _table(["Id", "When", "What", "Status"], [[_id(f), esc(f.get("at") or "unknown"), esc(f.get("text")), esc(f.get("status") or "")] for f in timeline]) if timeline else ["None.", ""]

    L += ["## Actions", ""]
    acts = kind("action")
    L += _table(["Id", "Action", "Owner", "Due", "Status"], [[_id(f), esc(f.get("text")), esc(f.get("owner") or "none named"), esc(f.get("due") or "none given"), esc(f.get("status") or "")] for f in acts]) if acts else ["None.", ""]

    L += ["## Decisions", ""]
    decs = kind("decision")
    L += _table(["Id", "Decision", "Owner", "Status"], [[_id(f), esc(f.get("text")), esc(f.get("owner") or ""), esc(f.get("status") or "")] for f in decs]) if decs else ["None.", ""]

    L += ["## Contradictions and ambiguities", ""]
    amb = kind("contradiction") + kind("ambiguity")
    rows = []
    for f in amb:
        cw = f.get("conflictsWith") if isinstance(f.get("conflictsWith"), list) else []
        rows.append([_id(f), esc(f.get("kind")), esc(f.get("text")),
                     ", ".join(f"`{re.sub(r'[^A-Za-z0-9_-]', '?', str(c))}`" + (f" ({esc(by_id[str(c)].get('text'))})" if str(c) in by_id else "") for c in cw) or "none"])
    L += _table(["Id", "Kind", "What", "Conflicts with"], rows) if rows else ["None.", ""]

    L += ["## Open questions", ""]
    oq = kind("open_question")
    L += _table(["Id", "Question", "Owner"], [[_id(f), esc(f.get("text")), esc(f.get("owner") or "")] for f in oq]) if oq else ["None.", ""]

    L += ["## Deferred facts", "", "Left out of the video on purpose; this report is their record.", ""]
    L += _table(["Id", "Kind", "Fact", "Reason"], [[_id(f), esc(f.get("kind")), esc(f.get("text")), f"deferred to report ({esc(f.get('importance'))} importance)"] for f in deferred]) if deferred else ["None.", ""]

    L += ["## All facts", ""]
    L += _table(["Id", "Kind", "Importance", "Status", "Fact", "Quote", "In video"],
                [[_id(f), esc(f.get("kind")), esc(f.get("importance")), esc(f.get("status") or ""), esc(f.get("text")),
                  esc(f.get("quote") or ""), covered(f)] for f in facts]) if facts else ["No facts.", ""]
    return "\n".join(L).rstrip() + "\n"
