// Deterministic code generator for src/visuals/{capabilities,registry,views,catalog}.*
// Node-only (uses fs/path); never imported by the Remotion bundle or files under src/visuals/.
import fs from 'node:fs';
import path from 'node:path';

export type VisualEntry = {
  slug: string;
  ident: string;
  pascal: string;
  has2D: boolean;
  has3D: boolean;
  lazy2dOverride?: boolean;
};

export type OrderConfig = {
  registry: string[];
  schema: string[];
  docs: string[];
  eager2d: string[];
};

export const GENERATED_FILES = ['capabilities.ts', 'registry.ts', 'views.tsx', 'catalog.ts'] as const;
export type GeneratedFile = (typeof GENERATED_FILES)[number];

const HEADER = '// GENERATED by `tsx src/cli.ts gen-visuals` (via `make docs`). Do not edit directly.\n';
const SLUG_RE = /^[a-z][a-z0-9-]*$/;
const IDENT_KEY_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const RESERVED_WORDS = new Set([
  'await', 'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete',
  'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'implements',
  'import', 'in', 'instanceof', 'interface', 'let', 'new', 'null', 'package', 'private', 'protected',
  'public', 'return', 'static', 'super', 'switch', 'this', 'throw', 'true', 'try', 'type', 'typeof',
  'var', 'void', 'while', 'with', 'yield',
]);

export const toIdent = (slug: string): string => {
  const camel = slug.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
  return RESERVED_WORDS.has(camel) ? `${camel}_` : camel;
};

export const toPascal = (slug: string): string =>
  slug
    .split('-')
    .map((seg) => (seg ? seg[0].toUpperCase() + seg.slice(1) : ''))
    .join('');

export const propKey = (slug: string): string => (IDENT_KEY_RE.test(slug) ? slug : `'${slug}'`);

const propAccess = (obj: string, slug: string): string =>
  IDENT_KEY_RE.test(slug) ? `${obj}.${slug}` : `${obj}['${slug}']`;

/** Discover all visual folders under `visualsDir` containing `capabilities.ts` and validate required files. */
export const discoverVisuals = (visualsDir: string): VisualEntry[] => {
  if (!fs.existsSync(visualsDir)) {
    throw new Error(`visuals directory not found: ${visualsDir}`);
  }
  const dirs = fs
    .readdirSync(visualsDir, {withFileTypes: true})
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

  const entries: VisualEntry[] = [];
  for (const slug of dirs) {
    const dir = path.join(visualsDir, slug);
    const capPath = path.join(dir, 'capabilities.ts');
    if (!fs.existsSync(capPath)) {
      throw new Error(`unexpected directory src/visuals/${slug} without capabilities.ts (keep shared helpers outside src/visuals/)`);
    }
    if (!SLUG_RE.test(slug)) {
      throw new Error(`invalid visual directory name "${slug}" (must match ${SLUG_RE})`);
    }
    const missing = ['schema.ts', 'semantics.ts', 'meta.ts', 'catalog.ts'].filter(
      (f) => !fs.existsSync(path.join(dir, f)),
    );
    if (missing.length) {
      throw new Error(`src/visuals/${slug} is missing required file(s): ${missing.join(', ')}`);
    }
    const has2D = fs.existsSync(path.join(dir, 'View2D.tsx'));
    const has3D = fs.existsSync(path.join(dir, 'View3D.tsx'));
    if (!has2D && !has3D) {
      throw new Error(`src/visuals/${slug} must provide at least View2D.tsx or View3D.tsx`);
    }
    const capText = fs.readFileSync(capPath, 'utf8');
    const lazyMatch = /\blazy2d\s*:\s*(true|false)\b/.exec(capText);
    entries.push({
      slug,
      ident: toIdent(slug),
      pascal: toPascal(slug),
      has2D,
      has3D,
      lazy2dOverride: lazyMatch ? lazyMatch[1] === 'true' : undefined,
    });
  }
  if (!entries.length) {
    throw new Error(`no visual types discovered under ${visualsDir}`);
  }
  return entries;
};

/** Read and validate `order.json` against discovered visual slugs. */
export const readOrderConfig = (visualsDir: string, discoveredSlugs: readonly string[]): OrderConfig => {
  const orderPath = path.join(visualsDir, 'order.json');
  const empty: OrderConfig = {registry: [], schema: [], docs: [], eager2d: []};
  if (!fs.existsSync(orderPath)) return empty;

  const raw = JSON.parse(fs.readFileSync(orderPath, 'utf8')) as Partial<OrderConfig>;
  const known = new Set(discoveredSlugs);
  const validateList = (key: keyof OrderConfig): string[] => {
    const val = raw[key];
    if (val === undefined) return [];
    if (!Array.isArray(val) || val.some((x) => typeof x !== 'string')) {
      throw new Error(`order.json "${key}" must be an array of visual slugs`);
    }
    const seen = new Set<string>();
    for (const slug of val) {
      if (!known.has(slug)) {
        throw new Error(`order.json "${key}" references unknown visual "${slug}"`);
      }
      if (seen.has(slug)) {
        throw new Error(`order.json "${key}" lists duplicate visual "${slug}"`);
      }
      seen.add(slug);
    }
    return val;
  };
  return {
    registry: validateList('registry'),
    schema: validateList('schema'),
    docs: validateList('docs'),
    eager2d: validateList('eager2d'),
  };
};

/** Keep `preferred` entries first, appending any unlisted discovered slugs in sorted order. */
export const resolveOrder = (preferred: readonly string[], discoveredSlugs: readonly string[]): string[] => {
  const inPref = new Set(preferred);
  const tail = discoveredSlugs.filter((s) => !inPref.has(s)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return [...preferred, ...tail];
};

const emitCapabilities = (ordered: readonly VisualEntry[]): string => {
  const imports = ordered.map((v) => `import {capabilities as ${v.ident}} from './${v.slug}/capabilities';`).join('\n');
  const mapEntries = ordered
    .map((v) => {
      const k = propKey(v.slug);
      return k === v.ident ? `  ${k},` : `  ${k}: ${v.ident},`;
    })
    .join('\n');

  return `${HEADER}// What each visual type supports. Pure leaf (no schema or React behind it), so src/schema.ts can derive its rules from it
// without an import cycle; each type's own list is src/visuals/<type>/capabilities.ts (re-exported by its meta).
import {LOCAL_CAPABILITIES} from '../visuals-local/capabilities';
${imports}

export type Capabilities = {
  /** Where the type can be drawn: layers3d is 3D only. */
  modes: readonly ('2d' | '3d')[];
  /** The scene may set \`continues\` (carry the previous scene's diagram across the cut): false, or '2d' (not in 3D yet). Only types whose parts have ids (graph, class, sequence). */
  continues: false | '2d';
  /** The scene may set \`focus\`: 'both' in 2D and 3D, '2d' only in 2D (mermaid, whose 3D view is flat), false never. */
  focus: false | '2d' | 'both';
  /** Arabic (right to left): 'yes' laid out mirrored, 'warn' drawn but not mirrored (the type's lint then says what to do). */
  rtl: 'yes' | 'warn';
  /** How the 3D overlay renders \`heading\`: 'banner' (default) or 'badge' (small mono label, used by callout). */
  headingStyle?: 'banner' | 'badge';
  /** Optional override for 2D view bundle loading (unlisted visuals default to lazy-loaded). */
  lazy2d?: boolean;
};

export const BUILTIN_CAPABILITIES = {
${mapEntries}
} satisfies Record<string, Capabilities>;
export type BuiltinCapType = keyof typeof BUILTIN_CAPABILITIES;

export const CAPABILITIES = {
  ...BUILTIN_CAPABILITIES,
  ...LOCAL_CAPABILITIES,
} satisfies Record<string, Capabilities>;
export type CapType = keyof typeof CAPABILITIES;
const entries = Object.entries(CAPABILITIES) as [CapType, Capabilities][];
const typesWhere = (f: (c: Capabilities) => boolean) => entries.filter(([, c]) => f(c)).map(([t]) => t);
type TypesWhere<C> = {[T in CapType]: (typeof CAPABILITIES)[T] extends C ? T : never}[CapType];

/** Types whose parts have ids (graph, class, sequence): they support \`continues\` and ids in \`focus\`. */
export const DIAGRAM_TYPES = typesWhere((c) => c.continues !== false) as TypesWhere<{continues: '2d'}>[];
/** Types that only exist in 3D scripts. */
export const THREE_D_TYPES = typesWhere((c) => !c.modes.includes('2d')) as TypesWhere<{modes: readonly ['3d']}>[];
/** How the 3D overlay renders a visual type's heading ('banner' by default, or 'badge' for callout). */
export const headingStyleOf = (t: CapType): 'banner' | 'badge' => (CAPABILITIES[t] as Capabilities).headingStyle ?? 'banner';
`;
};

const emitRegistry = (
  regOrdered: readonly VisualEntry[],
  schemaOrdered: readonly VisualEntry[],
  docsOrder: readonly string[],
): string => {
  const schemaImports = regOrdered
    .map((v) => `import {schema as ${v.ident}Schema} from './${v.slug}/schema';`)
    .join('\n');
  const semImports = regOrdered
    .map((v) => `import {describe as ${v.ident}Sem} from './${v.slug}/semantics';`)
    .join('\n');
  const metaImports = regOrdered
    .map((v) => `import {meta as ${v.ident}Meta} from './${v.slug}/meta';`)
    .join('\n');

  const schemasBody = schemaOrdered
    .map((v) => `  ${propKey(v.slug)}: ${v.ident}Schema,`)
    .join('\n');
  const registryBody = regOrdered
    .map((v) => `  ${propKey(v.slug)}: {schema: ${propAccess('SCHEMAS', v.slug)}, semantics: ${v.ident}Sem, meta: ${v.ident}Meta},`)
    .join('\n');
  const docsOrderList = docsOrder.map((s) => `'${s}'`).join(', ');

  return `${HEADER}// The pure list of visual types: schema + semantics + meta for each, with no React, remotion or three behind it
// (cli.ts loads it under plain node; test_semantics checks this). The rendering side is src/visuals/views.tsx.
// Both lists are exhaustive over the visual types, so a type missing from either is a compile error.
import {z} from 'zod';
import type {Visual} from '../types';
import type {Described, Semantics} from '../semantics/types';
import type {FocusTargets, LintCtx, LintResult, Meta} from './meta-types';
import type {ScriptVisual} from '../schema';
import {LOCAL_SCHEMAS, LOCAL_REGISTRY} from '../visuals-local/registry';
${schemaImports}
${semImports}
${metaImports}

/** Built-in type schemas in canonical schema order. */
export const BUILTIN_SCHEMAS = {
${schemasBody}
};
type BuiltinSchemas = (typeof BUILTIN_SCHEMAS)[keyof typeof BUILTIN_SCHEMAS];

/** The schema of each built-in + user-local type. */
const SCHEMAS = {
  ...BUILTIN_SCHEMAS,
  ...LOCAL_SCHEMAS,
};
type Schemas = (typeof SCHEMAS)[keyof typeof SCHEMAS];

export const BuiltinVisualSchema = z.discriminatedUnion('type', Object.values(BUILTIN_SCHEMAS) as [BuiltinSchemas, ...BuiltinSchemas[]])
  .describe('Built-in visual types; "type" selects the shape');

export const VisualSchema = z.discriminatedUnion('type', Object.values(SCHEMAS) as [Schemas, ...Schemas[]])
  .describe('What is drawn in the scene; "type" selects the shape');

export type BuiltinVisualType = keyof typeof BUILTIN_SCHEMAS;
export type VisualType = Visual['type'];

export type Entry<T extends VisualType> = {schema: (typeof SCHEMAS)[T]; semantics: Semantics<T>; meta: Meta<T>};
export const BUILTIN_REGISTRY: {[T in BuiltinVisualType]: Entry<T>} = {
${registryBody}
};

export const REGISTRY: {[T in VisualType]: Entry<T>} = {
  ...BUILTIN_REGISTRY,
  ...LOCAL_REGISTRY,
} as {[T in VisualType]: Entry<T>};

/** Canonical display order in SKILL.md visual-types table and matrix. */
export const DOCS_ORDER = [${docsOrderList}] as const satisfies readonly BuiltinVisualType[];

export const describe = (visual: Visual, prev?: Visual, rendered?: {layout?: unknown}): Described =>
  (REGISTRY[visual.type].semantics as (v: Visual, p?: Visual, r?: {layout?: unknown}) => Described)(visual, prev, rendered);

/** Style checks of one scene: the type's own lint. Only warns for now (a script that passed the schema must not start failing);
 *  \`errors\` is for rules a type decides are fatal. What a type supports (focus, continues, 3D) is checked by the schema, from
 *  its capabilities. Messages carry no "video/scene: " prefix. */
export const lintScene = (sc: {visual: ScriptVisual; narration: string}, ctx: Omit<LintCtx, 'narration'>): LintResult => {
  const m = REGISTRY[sc.visual.type].meta as Meta<VisualType>;
  return m.lint(sc.visual as never, {...ctx, narration: sc.narration});
};

/** Focus targets (part ids and optional [from, to] links) for a visual, or null when dynamic/unsupported. */
export const focusTargetsOf = (v: ScriptVisual): FocusTargets | null => {
  const m = REGISTRY[v.type].meta as Meta<VisualType>;
  return m.focusTargets ? m.focusTargets(v as never) : null;
};
`;
};

const emitViews = (regOrdered: readonly VisualEntry[], eager2d: readonly string[]): string => {
  const bySlug = new Map(regOrdered.map((v) => [v.slug, v]));
  const eagerSet = new Set(eager2d);
  const isEager2D = (v: VisualEntry): boolean =>
    v.lazy2dOverride !== undefined ? !v.lazy2dOverride : eagerSet.has(v.slug);

  const eagerList = [
    ...eager2d.map((s) => bySlug.get(s)).filter((v): v is VisualEntry => !!v && v.has2D && isEager2D(v)),
    ...regOrdered.filter((v) => v.has2D && !eagerSet.has(v.slug) && isEager2D(v)),
  ];
  const lazy2dList = regOrdered.filter((v) => v.has2D && !isEager2D(v));
  const lazy3dList = regOrdered.filter((v) => v.has3D);

  const eagerImports = eagerList
    .map((v) => `import {View2D as ${v.pascal}2D} from './${v.slug}/View2D';`)
    .join('\n');
  const lazy2dDecls = lazy2dList
    .map((v) => `const ${v.pascal}2D = lazyView<View2DProps<'${v.slug}'>>(() => import('./${v.slug}/View2D').then((m) => ({default: m.View2D})), '${v.slug}-2d');`)
    .join('\n');
  const lazy3dDecls = lazy3dList
    .map((v) => `const ${v.pascal}3D = lazyView<Visual3DProps<Extract<Visual, {type: '${v.slug}'}>>>(() => import('./${v.slug}/View3D').then((m) => ({default: m.View3D})), '${v.slug}-3d');`)
    .join('\n');
  const viewsEntries = regOrdered
    .map((v) => `  ${propKey(v.slug)}: {View2D: ${v.has2D ? `${v.pascal}2D` : 'null'}, View3D: ${v.has3D ? `${v.pascal}3D` : 'null'}},`)
    .join('\n');

  return `${HEADER}// The rendering list: each visual type's 2D and 3D view. SceneBody (visuals.tsx) and Scene3D (three/Scene3D.tsx) look
// their component up here. The pure list (registry.ts) has the schema and semantics. This is the only place that
// imports the views, so a type that has none fails to compile once the Record is exhaustive.
// Heavy and newly added 2D/3D views are lazy-loaded via React.lazy + Remotion delayRender so tabs only parse/load active chunks.
import React from 'react';
import type {Visual} from '../types';
import type {Visual3DProps} from '../three/common';
import type {BuiltinVisualType, VisualType} from './registry';
import type {View2DProps} from './props';
import {lazyView} from './lazy-view';
import {LOCAL_VIEWS} from '../visuals-local/views';

export {lazyView};

// Lightweight 2D views kept eager in main bundle
${eagerImports}

// Heavy & extension 2D views code-split on demand
${lazy2dDecls}

// 3D views code-split on demand (Three.js + @react-three/fiber never parsed on 2D renders)
${lazy3dDecls}

type VisualOf<T extends VisualType> = Extract<Visual, {type: T}>;
/** \`View2D\` is null for a type with no 2D picture of its own (layers3d/surface3d are 3D only);
 *  \`View3D\` is null for a type that cannot be drawn in 3D (schema rejects it in a 3D script). */
export type ViewSet<T extends VisualType> = {View2D: React.FC<View2DProps<T>> | null; View3D: React.FC<Visual3DProps<VisualOf<T>>> | null};

const BUILTIN_VIEWS: {[T in BuiltinVisualType]: ViewSet<T>} = {
${viewsEntries}
};

export const VIEWS: {[T in VisualType]: ViewSet<T>} = {
  ...BUILTIN_VIEWS,
  ...LOCAL_VIEWS,
} as {[T in VisualType]: ViewSet<T>};

/** The views of a visual's type, typed loosely for the dispatchers (the Record above is checked per type). */
export const viewsOf = (v: Visual) => VIEWS[v.type] as {View2D: React.FC<View2DProps<any>> | null; View3D: React.FC<Visual3DProps<any>> | null};
`;
};

const emitCatalog = (regOrdered: readonly VisualEntry[]): string => {
  const imports = regOrdered
    .map((v) => `import {catalog as ${v.ident}} from './${v.slug}/catalog';`)
    .join('\n');
  const entries = regOrdered
    .map((v) => {
      const k = propKey(v.slug);
      return k === v.ident ? `  ${k},` : `  ${k}: ${v.ident},`;
    })
    .join('\n');

  return `${HEADER}// Exhaustive compile-time catalog registry of every visual construct (\`Record<VisualType, CatalogEntry<...>>\`).
// Must NOT import React, Remotion, or Three (checked by test_semantics.py).
import type {BuiltinVisualType, VisualType} from './registry';
import type {CatalogEntry} from './catalog-types';
import {LOCAL_CATALOG} from '../visuals-local/catalog';
${imports}

export type CatalogMap = {[K in VisualType]: CatalogEntry<K>};

export const BUILTIN_CATALOG: {[K in BuiltinVisualType]: CatalogEntry<K>} = {
${entries}
};

export const CATALOG: CatalogMap = {
  ...BUILTIN_CATALOG,
  ...LOCAL_CATALOG,
} as CatalogMap;

export type AnyCatalogEntry = CatalogEntry<VisualType>;
`;
};

/** Generate the exact source contents of all 4 visual registry files for `visualsDir`. */
export const generateVisualFiles = (visualsDir: string): Record<GeneratedFile, string> => {
  const discovered = discoverVisuals(visualsDir);
  const bySlug = new Map(discovered.map((v) => [v.slug, v]));
  const slugs = discovered.map((v) => v.slug);
  const order = readOrderConfig(visualsDir, slugs);

  const regOrder = resolveOrder(order.registry, slugs);
  const schemaOrder = resolveOrder(order.schema, slugs);
  const docsOrder = resolveOrder(order.docs, slugs);

  const regEntries = regOrder.map((s) => bySlug.get(s)!);
  const schemaEntries = schemaOrder.map((s) => bySlug.get(s)!);

  return {
    'capabilities.ts': emitCapabilities(regEntries),
    'registry.ts': emitRegistry(regEntries, schemaEntries, docsOrder),
    'views.tsx': emitViews(regEntries, order.eager2d),
    'catalog.ts': emitCatalog(regEntries),
  };
};

const LOCAL_STUBS: Record<GeneratedFile, string> = {
  'capabilities.ts': "// Auto-created stub for user-local visuals (gitignored).\nexport const LOCAL_CAPABILITIES = {} as const;\n",
  'registry.ts': "// Auto-created stub for user-local visuals (gitignored).\nexport const LOCAL_SCHEMAS = {};\nexport const LOCAL_REGISTRY = {};\n",
  'views.tsx': "// Auto-created stub for user-local visuals (gitignored).\nexport const LOCAL_VIEWS = {};\n",
  'catalog.ts': "// Auto-created stub for user-local visuals (gitignored).\nexport const LOCAL_CATALOG = {};\n",
};

/** Ensure gitignored `src/visuals-local/` bridge stubs exist so fresh checkouts typecheck cleanly. */
export const ensureLocalVisualStubs = (srcDir: string): void => {
  const localDir = path.join(srcDir, 'visuals-local');
  fs.mkdirSync(localDir, {recursive: true});
  for (const name of GENERATED_FILES) {
    const dest = path.join(localDir, name);
    if (!fs.existsSync(dest)) fs.writeFileSync(dest, LOCAL_STUBS[name], 'utf8');
  }
};

/** Write changed generated visual registry files under `visualsDir`. */
export const writeVisualFiles = (visualsDir: string): {updated: string[]; unchanged: string[]} => {
  ensureLocalVisualStubs(path.dirname(visualsDir));
  const generated = generateVisualFiles(visualsDir);
  const updated: string[] = [];
  const unchanged: string[] = [];
  for (const name of GENERATED_FILES) {
    const dest = path.join(visualsDir, name);
    const next = generated[name];
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
    if (cur === next) {
      unchanged.push(`src/visuals/${name}`);
    } else {
      fs.writeFileSync(dest, next, 'utf8');
      updated.push(`src/visuals/${name}`);
    }
  }
  return {updated, unchanged};
};

/** Return relative paths (`src/visuals/<file>`) that differ from freshly generated output. */
export const checkVisualFiles = (visualsDir: string): string[] => {
  const generated = generateVisualFiles(visualsDir);
  const stale: string[] = [];
  for (const name of GENERATED_FILES) {
    const dest = path.join(visualsDir, name);
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
    if (cur !== generated[name]) {
      stale.push(`src/visuals/${name}`);
    }
  }
  return stale;
};
