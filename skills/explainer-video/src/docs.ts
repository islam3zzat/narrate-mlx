// The visual-types section of SKILL.md, generated from each type's meta (docs + capabilities). Pure: `cli.ts docs` prints or splices it.
import {DOCS_ORDER, REGISTRY} from './visuals/registry';

const IND = '   '; // the block sits inside step 4 of the numbered list
export const BEGIN = IND + '<!-- visuals:begin (generated by `make docs` from src/visuals/<type>/meta.ts; edit the meta, not this block) -->';
export const END = IND + '<!-- visuals:end -->';

export const visualsSection = (): string => {
  const metas = DOCS_ORDER.map((t) => REGISTRY[t].meta);
  const table = [
    '| type | fields | use for |',
    '|---|---|---|',
    ...metas.map((m) => `| \`${m.type}\` | ${m.docs.fields} | ${m.docs.use} |`),
  ];
  const rules = metas.filter((m) => m.docs.rules).flatMap((m) => ['', `**\`${m.type}\` rules:**`, ...m.docs.rules!.map((r) => `- ${r}`)]);
  const yes = (b: boolean) => (b ? 'yes' : '-');
  const matrix = [
    '| type | 2D | 3D | `continues` | `focus` | Arabic |',
    '|---|---|---|---|---|---|',
    ...metas.map(({type, capabilities: c}) => {
      const focus = c.focus === 'both' ? '2D and 3D' : c.focus === '2d' ? '2D only' : '-';
      const ar = c.rtl === 'yes' ? 'mirrored' : 'not mirrored';
      return `| \`${type}\` | ${yes(c.modes.includes('2d'))} | ${yes(c.modes.includes('3d'))} | ${c.continues ? '2D only' : c.boardContinues ? 'whiteboard only' : '-'} | ${focus} | ${ar} |`;
    }),
  ];
  const body = [
    'Visual types (`visual.type`), with the fields each needs:',
    '',
    ...table,
    ...rules,
    '',
    'What each type supports (`continues` and `focus` are scene fields, see below):',
    '',
    ...matrix,
  ].map((l) => (l ? IND + l : l));
  return [BEGIN, ...body, END].join('\n');
};

/** SKILL.md text with the block between the markers replaced by the generated one. */
export const splice = (skill: string): string => {
  const a = skill.indexOf(BEGIN.slice(0, IND.length + 18)), b = skill.indexOf(END);
  if (a < 0 || b < a) throw new Error('SKILL.md has no <!-- visuals:begin --> ... <!-- visuals:end --> block');
  return skill.slice(0, a) + visualsSection() + skill.slice(b + END.length);
};
