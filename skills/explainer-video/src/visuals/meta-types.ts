// What each visual type says about itself (src/visuals/<type>/meta.ts): what it supports, and its own style checks.
// Pure (types only). The generic checks over these live in registry.ts (lintScene).
import type {ScriptVisual} from '../schema';
import type {Capabilities} from './capabilities';

export type {Capabilities};
export type LintCtx = {
  lang: 'en' | 'ar'; mode: '2d' | '3d';
  /** The scene's narration (as written in the script). */
  narration: string;
  /** A `continues` scene: per reveal slot (semantics.ts), true when it is carried from the previous scene (already on screen, so the narration need not say it). */
  carried?: boolean[];
};
/** Messages without the "video/scene: " prefix (the caller adds it). */
export type LintResult = {errors: string[]; warnings: string[]};

/** What goes into the visual-types section of SKILL.md (generated by `cli.ts docs`; wording is what the skill reader sees). */
export type Docs = {
  /** The "fields" cell of the table: backticked field names, `?` marks optional ones. */
  fields: string;
  /** The "use for" cell: when to pick this type, with its limits. */
  use: string;
  /** Longer rules listed under the table, one markdown bullet each (only types that need them). */
  rules?: string[];
};

export type FocusTargets = {ids: readonly string[]; links?: readonly [string, string][]};

export type Meta<T extends ScriptVisual['type']> = {
  readonly type: T;
  readonly capabilities: Capabilities;
  readonly docs: Docs;
  readonly lint: (visual: Extract<ScriptVisual, {type: T}>, ctx: LintCtx) => LintResult;
  /** Ids (and optional [from, to] links) that `focus` may name; return null when targets are only known after rendering (e.g. mermaid). */
  readonly focusTargets?: (visual: Extract<ScriptVisual, {type: T}>) => FocusTargets | null;
};

export const NO_LINT: LintResult = {errors: [], warnings: []};
